import assert from 'node:assert/strict';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import {createServer} from 'vite';

const server=await createServer({server:{middlewareMode:true},appType:'custom',logLevel:'silent'});
const cases=[];
try{
  const {fleetRiskRowsByVessel:match,fleetRiskCardNotice:notice,fleetRiskCardDescription:describe}=await server.ssrLoadModule('/src/fleetRisk/cardRisk.ts');
  const {REFERENCE_FLEET}=await server.ssrLoadModule('/supabase/functions/fleet-risk/referenceFleet.ts');
  const {createInitialData}=await server.ssrLoadModule('/src/data/seed.ts');
  const {parseFleetRiskState}=await server.ssrLoadModule('/src/fleetRisk/model.ts');
  const now='2026-11-10T23:02:30.000Z';
  const rows=REFERENCE_FLEET.map((row,index)=>({...row,risk:['HRS','SRS','LRS'][index%3],status:'ok',priority:'No Priority',retrievedAt:now,companyName:'Synthetic QA',companyImo:'0882415',windowFrom:null,windowTo:null,sourceUpdatedAt:null,sourceUrl:'https://apcis.tmou.org/public/'}));
  const snapshot={id:'00000000-0000-4000-8000-000000000001',trigger:'scheduled',company:{name:'Synthetic QA',imo:'0882415',performance:'Medium'},queryStartedAt:'2026-11-10T23:00:00.000Z',queryCompletedAt:now,rosterRetrievedAt:now,count:rows.length,rows,coverage:{referenceCount:rows.length,missingReferenceImos:[],addedReferenceImos:[]}};
  const state=parseFleetRiskState({snapshot,attempt:null,serverTime:now,nextScheduledAt:'2026-11-11T23:00:00.000Z'});
  const vessels=createInitialData().vessels,before=JSON.stringify(vessels),matched=match(vessels,state.snapshot);
  assert.equal(REFERENCE_FLEET.length,39);assert.equal(matched.size,39,'all reference identities match the committed vessel catalog');
  assert.equal(new Set([...matched.values()].map(r=>r.imo)).size,39);
  assert.equal(JSON.stringify(vessels),before,'display enrichment does not mutate vessel records');
  cases.push('identity: all 39 reference IMO identities match the committed catalog without writes (synthetic grades)');
  const vessel=vessels.find(v=>v.fullName===rows[0].name),one={...snapshot,rows:[rows[0]],count:1};
  assert.equal(match([{...vessel,fullName:` ${vessel.fullName.toLowerCase()} `}],one).size,1);
  assert.equal(match([{...vessel,fullName:'',shortName:rows[0].name}],one).size,0,'no short-name guessing');
  assert.equal(match([{...vessel,fullName:rows[0].name+' EXTRA'}],one).size,0,'no partial match');
  assert.equal(match([vessel,{...vessel,id:'other'}],one).size,0,'ambiguous local names are unknown');
  assert.equal(match([vessel,{...vessel,fullName:'different'}],one).size,0,'duplicate local IDs are unknown');
  assert.equal(match([vessel],{...one,rows:[rows[0],{...rows[1],name:rows[0].name}]}).size,0,'ambiguous official names are unknown');
  assert.equal(match(vessels,null).size,0);
  cases.push('identity: missing, partial, duplicate local/official names and IDs fail closed');
  assert.equal(notice(state,'',false),'');
  assert.equal(notice({...state,serverTime:'2026-11-11T23:01:00Z'},'',false),'待更新');
  assert.equal(notice({...state,attempt:{status:'running'}},'',false),'更新中');
  assert.equal(notice({...state,attempt:{status:'failed'}},'',false),'更新失敗');
  assert.equal(notice(state,'network failure',false),'讀取失敗');
  assert.match(describe(rows[0],''),/Tokyo MOU.*IMO.*台北/);
  assert.match(describe(undefined,''),/不代表低風險/);
  assert.doesNotMatch(describe(undefined,'讀取失敗'),/保留上次成功資料/,'no prior row must not claim a retained successful value');
  cases.push('freshness: scheduled boundary, running/failed/read failure and unknown description');
  const f=await server.ssrLoadModule('/src/vesselDashboardFilters.ts');
  const base=f.emptyVesselFilterState(),only={...base,tokyoHrsOnly:true};
  const facts={id:'v',selfManaged:false,shipType:'A',attentionGroup:'other',selectedForMeeting:false,supervisorIds:[]};
  assert.equal(f.hasActiveVesselFilters(only),true);assert.equal(f.hasActiveVesselFilters(base),false);
  for(const risk of ['HRS','SRS','LRS',null,undefined])assert.equal(f.matchesVesselFilterGroups({...facts,tokyoRisk:risk},only),risk==='HRS');
  assert.equal(f.matchesVesselFilterGroups({...facts,tokyoRisk:'HRS'},{...only,selfManagedOnly:true}),false);
  assert.equal(f.matchesVesselFilterGroups({...facts,tokyoRisk:'HRS'},{...only,shipTypes:['B']}),false);
  assert.equal(f.matchesVesselFilterGroups({...facts,tokyoRisk:'HRS'},{...only,supervisorIds:['qa']}),false);
  assert.equal(f.matchesVesselFilterGroups({...facts,tokyoRisk:'HRS'},{...only,meetingOnly:true}),false);
  assert.equal(f.matchesVesselFilterGroups(facts,base),true,'legacy consumers do not need risk facts');
  cases.push('filters: only explicit HRS; independent AND facets; legacy consumers unchanged');
  const {default:Controls}=await server.ssrLoadModule('/src/VesselFilterControls.tsx');
  const props={filters:base,shipTypes:[],supervisors:[],onChange:()=>{}};
  assert.doesNotMatch(renderToStaticMarkup(React.createElement(Controls,props)),/HRS船舶/,'other shared-control consumers retain existing UI');
  const shown=renderToStaticMarkup(React.createElement(Controls,{...props,showTokyoRisk:true}));
  assert.ok(shown.indexOf('選入會議')<shown.indexOf('HRS船舶'));
  cases.push('controls: dashboard opt-in and requested placement after meeting filter');
  console.log(JSON.stringify({status:'PASS',layer:'pure model and SSR; not production data',caseCount:cases.length,cases},null,2));
}finally{await server.close();}
