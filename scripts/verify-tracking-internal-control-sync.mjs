import assert from 'node:assert/strict';
import { createServer } from 'vite';
const vite = await createServer({server:{middlewareMode:true},appType:'custom',logLevel:'silent'});
try {
  const {createInitialData}=await vite.ssrLoadModule('/src/data/seed.ts');
  const {normalizeAppData}=await vite.ssrLoadModule('/src/normalize.ts');
  const ic=await vite.ssrLoadModule('/src/internalControlData.ts');
  const data=createInitialData(), actor={...data.users[0],id:'qa-owner',name:'QA OWNER',role:'owner',isActive:true,managedVesselIds:[]};
  data.users=[actor];
  const at='2026-09-24T00:00:00.000Z', later='2026-09-25T00:00:00.000Z';
  data.tasks=[];data.internalControlCases=[];
  const source={id:'source-1',kind:'supply',vesselId:data.vessels[0].id,referenceNo:'QA-001',description:'QA',applicationDate:'2026-09-24',urgency:'normal',progress:'初始',supplementalNotes:'',expectedDate:'2026-10-01',deliveryStatus:'not-delivered',isClosed:false,createdBy:actor.id,updatedBy:actor.id,createdAt:at,updatedAt:at,statusLogs:[]};
  const candidate={id:'case-1',vesselId:source.vesselId,trackingItemId:source.id,reportDate:'2026-09-24',expectedDate:'2026-10-02',reportSource:'日常',description:'人工核對後內容',priority:'低',category:'其他',isAware:false,status:'初始',departments:[data.settings.departments[0]],syncToTask:false,origin:'internal-control',isClosed:false,createdBy:actor.id,updatedBy:actor.id,createdAt:at,updatedAt:at,statusLogs:[]};
  ic.createInternalControlCases(data,[candidate],actor,at);
  data.trackingItems=[{...source,linkedCaseId:candidate.id,linkState:'active'},{...source,id:'sibling',kind:'engineering',referenceNo:'QA-001'}];
  const saved=ic.updateInternalControlCase(data,{...data.internalControlCases[0],isClosed:true,closedDate:'2026-09-25'},at,actor,later);
  assert.equal(data.trackingItems[0].isClosed,true,'mounted case-save helper must close the linked source');
  assert.equal(data.trackingItems[0].closedDate,saved.closedDate);
  assert.equal(data.trackingItems[0].deliveryStatus,'not-delivered');
  assert.equal(data.trackingItems[0].expectedDate,'2026-10-01');
  assert.equal(data.trackingItems[1].isClosed,false,'same-number sibling is independent');
  assert.equal(data.tasks.length,0,'closing never creates a task');
  const normalized=normalizeAppData(data);
  assert.equal(normalized.internalControlCases[0].trackingItemId,source.id,'normalization retains reciprocal source link');
  console.log('PASS case-entry closure converges exact source without business-field coupling');
  const reopened=ic.updateInternalControlCase(data,{...saved,isClosed:false},later,actor,'2026-09-26T00:00:00.000Z');
  assert.equal(data.trackingItems[0].isClosed,false);
  const linked=ic.updateInternalControlCase(data,{...reopened,syncToTask:true},reopened.updatedAt,actor,'2026-09-27T00:00:00.000Z',{categories:['其他'],expectedDate:reopened.expectedDate,ownerUserIds:[],isAbnormal:false});
  const task=data.tasks[0],previousTask=structuredClone(task);
  task.isClosed=true;task.closedDate='2026-09-28';task.closedBy=actor.id;
  ic.reconcileInternalControlAfterTaskSave(data,previousTask,task,actor,'2026-09-28T00:00:00.000Z');
  assert.equal(data.trackingItems[0].isClosed,true,'mounted task-save helper must close the linked source');
  assert.equal(data.trackingItems[0].closedDate,'2026-09-28');
  assert.equal(data.internalControlCases[0].id,linked.id);
  assert.equal(normalizeAppData(data).internalControlCases[0].trackingItemId,source.id);
  console.log('PASS task-entry closure retains reciprocal source link');
  const closedCase=data.internalControlCases[0];
  ic.updateInternalControlCase(data,{...closedCase,closedDate:'2026-09-29'},closedCase.updatedAt,actor,'2026-09-29T00:00:00.000Z');
  assert.equal(data.trackingItems[0].closedDate,'2026-09-29','explicit close-date correction must converge');
  assert.equal(data.tasks[0].closedDate,'2026-09-29');
  assert.ok(data.trackingItems[0].events.some(e=>e.action==='correct-close-date'&&e.before.closedDate==='2026-09-28'));
  const beforeDelete=structuredClone(data.trackingItems[0]);
  ic.deleteInternalControlCase(data,'case-1',data.internalControlCases[0].updatedAt,actor,'2026-09-30T00:00:00.000Z');
  assert.equal(data.trackingItems[0].id,beforeDelete.id,'case deletion retains source');
  assert.equal(data.trackingItems[0].linkState,'invalid','deletion records invalid link, never silently resyncs');
  assert.equal(data.trackingItems[0].linkedCaseId,'case-1','invalid ID retained for traceability');
  console.log('PASS close-date correction and invalid-link history');
  const {runTrackingCommand,prefillTrackingCase}=await vite.ssrLoadModule('/src/tracking/trackingWorkflow.ts');
  let deletion=structuredClone(normalized);
  // Reuse an open source with a live task, then exercise the mounted delete helper.
  deletion.trackingItems[0]={...source,linkedCaseId:'case-1',linkState:'active'};
  deletion.internalControlCases[0]={...candidate,isClosed:false,statusLogs:[]};
  ic.updateInternalControlCase(deletion,{...deletion.internalControlCases[0],syncToTask:true},at,actor,later,{categories:['其他'],expectedDate:candidate.expectedDate,ownerUserIds:[],isAbnormal:false});
  const removedTask=deletion.tasks[0];
  ic.closeLinkedInternalControlCaseAfterTaskDelete(deletion,removedTask,actor,'2026-09-30T00:00:00.000Z');
  deletion.tasks=[];
  assert.equal(deletion.trackingItems[0].linkState,'invalid','task deletion must explicitly invalidate source linkage');
  assert.equal(deletion.trackingItems[0].isClosed,false,'deleting task must not invent source completion');
  assert.equal(deletion.internalControlCases[0].trackingLinkState,'invalid');
  assert.equal(normalizeAppData(deletion).internalControlCases[0].trackingLinkState,'invalid');
  const resync=prefillTrackingCase(deletion,deletion.trackingItems[0],'replacement').item;
  resync.departments=[data.settings.departments[0]];
  deletion=runTrackingCommand(deletion,{type:'sync',items:[{id:source.id,expectedUpdatedAt:deletion.trackingItems[0].updatedAt,item:resync}]},{actorId:actor.id,at:'2026-10-01T00:00:00.000Z',operationId:'explicit-resync'});
  assert.equal(deletion.trackingItems[0].linkedCaseId,'replacement');
  assert.equal(deletion.tasks.length,0);
  assert.ok(deletion.trackingItems[0].events.some(e=>e.action==='invalidate-link'));
  console.log('PASS task deletion keeps source and invalid history; explicit resync only');
} finally { await vite.close(); }
